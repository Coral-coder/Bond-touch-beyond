"""Emits VFDFont.swift: [scalar: [row bits]] for small (5x9), mid (10x18) and big (15x27); bit 0 = leftmost."""
import sys
from font import SMALL, MID, BIG
def table(name, t):
    out = [f"    static let {name}: [UInt32: [UInt32]] = ["]
    for ch in sorted(t, key=ord):
        rows = [sum(1 << x for x, on in enumerate(r) if on) for r in t[ch]]
        while rows and rows[-1] == 0: rows.pop()          # trailing blank rows are implied
        out.append(f"        0x{ord(ch):04X}: [{', '.join(map(str, rows))}],")
    out.append("    ]"); return '\n'.join(out)
src = f"""// Generated by tools/vfd/gen_swift.py from tools/vfd/font_data.py. Do not edit by hand.
// An original 5x7 dot-matrix font (2 descender rows) and its Scale2x / Scale3x enlargements.
// Each glyph is a list of rows, top first; bit 0 is the leftmost pixel. Missing rows are blank.

enum VFDFont {{
{table('small', SMALL)}

{table('mid', MID)}

{table('big', BIG)}
}}
"""
open(sys.argv[1], 'w').write(src); print(len(src), 'bytes')
